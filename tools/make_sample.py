"""Write the bundled synthetic reflection list.

    python tools/make_sample.py

An fcc phase (a = 4.0495 A, the cell of aluminium), Cu K-alpha-1.  The widths come
from the program's own forward model for known D = 45 nm and es = 0.12 % with a
pseudo-Voigt profile, then get 2.5 % of Gaussian noise from a fixed seed.  One
reflection is widened by a further 18 % - as stacking faults would do - and marked
as not used, so that the plot shows what excluding a point does.
"""

from __future__ import annotations

import math
import random
from pathlib import Path

from sizeout_demo.domain import CU_KA1, Instrument, Profile, Quantity, from_microstructure

OUT = (
    Path(__file__).resolve().parents[1]
    / "src"
    / "sizeout_demo"
    / "data"
    / "sample_reflections.csv"
)
CELL = 4.0495  # Angstrom
SIZE, STRAIN = 45.0, 0.12  # nm, %
NOISE = 0.025
SEED = 20261114
FAULTED = (3, 3, 1)
HKL = [
    (1, 1, 1),
    (2, 0, 0),
    (2, 2, 0),
    (3, 1, 1),
    (2, 2, 2),
    (4, 0, 0),
    (3, 3, 1),
    (4, 2, 0),
    (4, 2, 2),
]


def two_theta(hkl: tuple[int, int, int]) -> float:
    d = CELL / math.sqrt(sum(i * i for i in hkl))
    return 2.0 * math.degrees(math.asin(CU_KA1 / (2.0 * d)))


def main() -> None:
    rng = random.Random(SEED)
    inst = Instrument()
    lines = [
        "# title: Synthetic fcc phase (a = 4.0495 A), Cu K-alpha-1",
        f"# generated by tools/make_sample.py: D = {SIZE:g} nm, es = {STRAIN:g} %, "
        f"pseudo-Voigt, {NOISE:.1%} noise, seed {SEED}",
        f"# {''.join(map(str, FAULTED))} widened by 18 % (stacking faults) and not used",
        "h,k,l,two_theta,fwhm,use",
    ]
    for hkl in HKL:
        tt = two_theta(hkl)
        est = from_microstructure(
            Quantity(SIZE), Quantity(STRAIN), Quantity(tt), inst, Profile.PSEUDO_VOIGT
        )
        assert est.broadening.total is not None
        width = est.broadening.total.value * (1.0 + rng.gauss(0.0, NOISE))
        use = hkl != FAULTED
        if not use:
            width *= 1.18
        lines.append(f"{hkl[0]},{hkl[1]},{hkl[2]},{tt:.4f},{width:.5f},{int(use)}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
